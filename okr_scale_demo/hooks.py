    def _manager_user(self, key):
        parent = next(p[5] for p in C.PEOPLE if p[0] == key)
        return self.users[parent] if parent else self.users['admin']

    def _create_objective(self, spec, cycle, approval_dt=None, extra=None):
        env = self.env
        level = spec['level']
        vals = {
            'name': spec['name'],
            'cycle_id': cycle.id,
            'company_id': self.company.id,
            'level': level,
            'okr_type': spec['okr_type'],
            'visibility': spec['visibility'],
            'description': spec.get('description') or False,
            'tag_ids': [Command.set([self.tags[t].id for t in spec['tags']])],
            'contributor_user_ids': [Command.set([self.users[u].id for u in spec['contributor_users']])],
            'contributor_department_ids': [Command.set([self.depts[d].id for d in spec['contributor_depts']])],
        }
        if level == 'company':
            owner = self.users[spec['owner']]
            vals.update(employee_id=False, department_id=False, owner_id=owner.id)
            approver = self.users['admin']
        elif level == 'department':
            department = self.depts[spec['dept']]
            owner = department.manager_id.user_id
            vals.update(employee_id=False, department_id=department.id, owner_id=owner.id)
            approver = self.users['ceo']
        else:
            employee = self.emps[spec['owner']]
            owner = employee.user_id
            vals.update(employee_id=employee.id, owner_id=owner.id)
            approver = self._manager_user(spec['owner'])
        if spec.get('parent'):
            vals['parent_key_result_id'] = self.krs[spec['parent']].id
        kr_commands = []
        for sequence, kr in enumerate(spec['krs'], 1):
            kr_owner = self.users[kr['owner']] if kr['owner'] else owner
            kr_commands.append(Command.create({
                'name': kr['name'],
                'sequence': sequence * 10,
                'metric_type': kr['metric'],
                'unit': kr['unit'] or False,
                'start_value': kr['start'],
                'target_value': kr['target'],
                'current_value': kr['start'],
                'weight': kr['weight'],
                'progress_method': kr['method'],
                'owner_id': kr_owner.id,
                'contributor_ids': [Command.set([self.users[u].id for u in kr['contributors']])],
            }))
        vals['key_result_ids'] = kr_commands
        vals.update(extra or {})
        objective = env['okr.scale.objective'].create(vals)
        self._register(spec, objective)
        self._apply_state(objective, spec.get('state', 'running'), approver, approval_dt)
        return objective

    def _register(self, spec, objective):
        self.objectives[spec['key']] = objective
        for kr_spec, kr in zip(spec['krs'], objective.key_result_ids.sorted(lambda k: (k.sequence, k.id))):
            self.krs[kr_spec['key']] = kr
            self.kr_specs[kr.id] = dict(kr_spec, dept=self._objective_dept_key(objective))

    def _objective_dept_key(self, objective):
        for key, department in self.depts.items():
            if department == objective.department_id:
                return key
        return 'bgd'

    def _apply_state(self, objective, state, approver, approval_dt):
        if state == 'running':
            objective.write({'state': 'running', 'approved_by_id': approver.id,
                             'approval_date': approval_dt or fields.Datetime.now()})
        elif state == 'to_approve':
            objective.action_submit()

    def _value_for(self, kr_spec, ratio):
        """Value reached at ``ratio`` (0..1+) of the way from start to target, nicely rounded."""
        start, target = kr_spec['start'], kr_spec['target']
        if kr_spec['metric'] == 'boolean':
            return 1.0 if ratio >= 1 else 0.0
        value = start + (target - start) * ratio
        return self._round(kr_spec, value)

    @staticmethod
    def _round(kr_spec, value):
        span = abs(kr_spec['target'] - kr_spec['start'])
        whole = kr_spec['metric'] == 'number' and float(kr_spec['start']).is_integer() \
            and float(kr_spec['target']).is_integer()
        if span >= 20 or (whole and span >= 3):
            return float(round(value))
        if span >= 2:
            return round(value, 1)
        return round(value, 2)

    def _checkin(self, kr, user, day, value, confidence, achievements=False, blockers=False, next_steps=False,
                 weekly=None):
        confidence = int(max(1, min(10, confidence)))
        mood = 'great' if confidence >= 9 else 'good' if confidence >= 7 else 'neutral' if confidence >= 5 \
            else 'struggling'
        checkin = self.env['okr.scale.checkin'].create({
            'key_result_id': kr.id,
            'user_id': user.id,
            'date': day,
            'new_value': value,
            'confidence': str(confidence),
            'mood': mood,
            'achievements': achievements or False,
            'blockers': blockers or False,
            'next_steps': next_steps or False,
            'weekly_id': weekly.id if weekly else False,
        })
        checkin.action_submit()
        return checkin

    def _series(self, objective, dates, approval_dt):
        """History of a past objective: check-ins on ``dates`` going from start to the final value."""
        for kr in objective.key_result_ids:
            spec = self.kr_specs[kr.id]
            if spec['method'] != 'manual' or spec['final'] is None:
                continue
            final = spec['final']
            span = spec['target'] - spec['start']
            final_ratio = (final - spec['start']) / span if span else 1.0
            confidence_base = 8 if final_ratio >= 0.9 else 7 if final_ratio >= 0.6 else 5
            for index, day in enumerate(dates, 1):
                share = index / len(dates)
                if index == len(dates):
                    value = final
                elif spec['metric'] == 'boolean':
                    value = 1.0 if final >= 1 and share >= 0.7 else 0.0
                else:
                    curve = min(1.0, share ** 0.9 + self.rnd.uniform(-0.04, 0.04))
                    value = self._round(spec, spec['start'] + (final - spec['start']) * max(0.0, curve))
                confidence = confidence_base + self.rnd.choice((-1, 0, 0, 1))
                self._checkin(kr, kr.owner_id, day, value, confidence,
                              achievements=self.rnd.choice(C.ACHIEVEMENTS[spec['dept']]),
                              next_steps=self.rnd.choice(C.NEXT_STEPS[spec['dept']]))

    # ------------------------------------------------------------------
    # Year 2026 and Q3 2026
    # ------------------------------------------------------------------
    def _year(self):
        cycle = self.cycles['y2026']
        approval = local_dt(cycle.date_start + timedelta(days=1))
        dates = []
        for month in range(1, 10):
            day = (cycle.date_start.replace(month=month + 1, day=1) - timedelta(days=1))
            if day <= self.today:
                dates.append(day)
        for spec in C.YEAR_OBJECTIVES:
            objective = self._create_objective(spec, cycle, approval)
            if dates:
                self._series(objective, dates, approval)

    def _q3(self):
        cycle = self.cycles['q3']
        approval = local_dt(cycle.date_start - timedelta(days=2))
        first_friday = cycle.date_start + timedelta(days=(4 - cycle.date_start.weekday()) % 7)
        dates = [first_friday + timedelta(days=7 * i) for i in range(14)]
        dates = [d for d in dates if d <= min(cycle.date_end, self.today)]
        for spec in C.Q3_OBJECTIVES:
            objective = self._create_objective(spec, cycle, approval)
            if dates:
                self._series(objective, dates, approval)
        # Grades, self-assessments, lessons learned, then close the cycle
        for spec in C.Q3_OBJECTIVES:
            objective = self.objectives[spec['key']]
            score = round(min(objective.progress, 100.0) / 100.0 * 20) / 20
            if spec['okr_type'] == 'aspirational':
                score = min(1.0, score + 0.05)
            objective.write({
                'final_score': score,
                'self_assessment': spec.get('self_assessment') or False,
                'lessons_learned': spec.get('lessons') or False,
            })
        if cycle.date_end < self.today:
            cycle.action_close()
            review = self.env['okr.scale.review'].create({
                'cycle_id': cycle.id,
                'review_type': 'final',
                'date': C.Q3_REVIEW['date'],
                'facilitator_id': self.users['admin'].id,
                'participant_ids': [Command.set([self.users[k].id for k in (
                    'ceo', 'admin', 'kd_mgr', 'cskh_mgr', 'ls_mgr', 'mkt_mgr', 'vh_mgr', 'ns_mgr', 'tc_mgr')])],
                'went_well': Markup(C.Q3_REVIEW['went_well']),
                'to_improve': Markup(C.Q3_REVIEW['to_improve']),
                'lessons': Markup(C.Q3_REVIEW['lessons']),
                'decisions': Markup(C.Q3_REVIEW['decisions']),
            })
            review.action_done()

