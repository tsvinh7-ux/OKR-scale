    def _q4_objectives(self):
        cycle = self.cycles['q4']
        approval = local_dt(cycle.date_start - timedelta(days=2))
        self.q4_approval = approval
        for spec in C.Q4_COMPANY + C.Q4_DEPARTMENTS + C.Q4_INDIVIDUALS:
            objective = self._create_objective(spec, cycle, approval)
            if spec.get('carried_from') in self.objectives:
                objective.carried_from_id = self.objectives[spec['carried_from']]
            for kr_key, previous in (spec.get('carried_krs') or {}).items():
                if previous in self.krs:
                    self.krs[kr_key].carried_from_id = self.krs[previous]
        for index, spec in enumerate(C.TEMPLATE_OBJECTIVES):
            self._template_objective(index, spec, cycle, approval)
        # Joint objective shared with the customer on the portal
        spec = C.PORTAL_OBJECTIVE
        objective = self._create_objective(spec, cycle, approval, extra={
            'partner_id': self.customer.id, 'portal_shared': True})
        for key, _name, _login, mode, _function in C.PORTAL['users']:
            objective._add_collaborators(self.users[key].partner_id, mode)
        self.portal_objective = objective

    def _template_objective(self, index, spec, cycle, approval):
        env = self.env
        Template = env['okr.scale.template']
        template = env.ref(spec['template'], raise_if_not_found=False)
        if not template or template._name != 'okr.scale.template' or not template.line_ids:
            template = Template.search([('level', '=', spec['level']), ('line_ids', '!=', False)], limit=1) \
                or Template.search([('line_ids', '!=', False)], limit=1)
        if not template:
            _logger.warning('OKR demo: no OKR template found, template objectives skipped')
            return
        if spec['level'] == 'individual':
            target = {'level': 'individual', 'employee_id': self.emps[spec['owner']].id,
                      'department_id': self.emps[spec['owner']].department_id.id}
            owner = self.users[spec['owner']]
            approver = self._manager_user(spec['owner'])
        else:
            department = self.depts[spec['dept']]
            target = {'level': 'department', 'department_id': department.id, 'employee_id': False}
            owner = department.manager_id.user_id
            approver = self.users['ceo']
        objective = env['okr.scale.objective']
        try:
            with env.cr.savepoint():
                Wizard = env['okr.scale.template.apply'].with_context(
                    default_template_id=template.id, default_level=target['level'])
                vals = Wizard.default_get(list(Wizard._fields))
                vals.update(target, template_id=template.id, cycle_id=cycle.id, owner_id=owner.id,
                            parent_key_result_id=self.krs[spec['parent']].id)
                action = Wizard.create(vals).action_apply()
                objective = objective.browse(action.get('res_id'))
        except Exception:  # noqa: BLE001 - fall back when the wizard API changes
            _logger.warning('OKR demo: template wizard failed, objective created directly', exc_info=True)
            objective = objective.create(dict(
                target, name=template.name, cycle_id=cycle.id, owner_id=owner.id, okr_type=template.okr_type,
                description=template.description, parent_key_result_id=self.krs[spec['parent']].id,
                key_result_ids=[Command.create({
                    'name': line.name, 'sequence': line.sequence, 'metric_type': line.metric_type,
                    'unit': line.unit, 'start_value': line.start_value, 'target_value': line.target_value,
                    'current_value': line.start_value, 'weight': line.weight, 'description': line.hint,
                    'owner_id': owner.id,
                }) for line in template.line_ids]))
            template.sudo().usage_count += 1
        if not objective:
            return
        objective.key_result_ids.write({'owner_id': owner.id})
        profiles = ['on', 'ahead', 'behind', 'on']
        krs = []
        for position, kr in enumerate(objective.key_result_ids.sorted(lambda k: (k.sequence, k.id))):
            krs.append(C.kr('tpl%s_k%s' % (index, position), kr.name, kr.start_value, kr.target_value, kr.unit,
                            metric=kr.metric_type, profile=profiles[position % len(profiles)]))
        fake_spec = {'key': 'tpl%s' % index, 'krs': krs}
        self._register(fake_spec, objective)
        self._apply_state(objective, spec['state'], approver, approval)

    def _project(self):
        env = self.env
        spec = C.PROJECT
        stages = {}
        for sequence, name in enumerate(spec['stages']):
            stages[name] = env['project.task.type'].create({
                'name': name, 'sequence': sequence, 'fold': name == spec['stages'][-1]})
        project = env['project.project'].create({
            'name': spec['name'],
            'user_id': self.users['vh_mgr'].id,
            'company_id': self.company.id,
            'privacy_visibility': 'employees',
            'type_ids': [Command.set([s.id for s in stages.values()])],
            'date_start': self.cycles['q4'].date_start,
            'date': self.cycles['q4'].date_end,
            'description': Markup('<p>Dự án trọng điểm quý 4: đặt lịch online và nhắc hẹn tự động cho toàn bộ '
                                  'phòng khám đối tác.</p>'),
        })
        kr = self.krs['vh_project']
        tasks = env['project.task']
        for sequence, (name, user_key, done, hours, stage) in enumerate(spec['tasks']):
            task = tasks.create({
                'name': name, 'project_id': project.id, 'stage_id': stages[stage].id, 'sequence': sequence,
                'user_ids': [Command.set(self.users[user_key].ids)], 'allocated_hours': hours,
                'okr_key_result_id': kr.id, 'date_deadline': self.cycles['q4'].date_start + timedelta(
                    days=7 + 7 * sequence),
            })
            if done:
                task.state = '1_done'
            elif stage == 'Kiểm thử':
                task.state = '02_changes_requested'
            tasks |= task
        kr.project_ids = [Command.link(project.id)]
        self.project = project

