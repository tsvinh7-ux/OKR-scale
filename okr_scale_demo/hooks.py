    def _rewards(self):
        env = self.env
        Item = env['okr.scale.reward.item']
        items = {}
        for sequence, (key, name, category, cost, icon, caption, description, stock) in enumerate(C.REWARD_ITEMS):
            items[key] = Item.create({
                'name': name, 'sequence': sequence, 'points_cost': cost, 'description': description,
                'category_id': env.ref('okr_scale_reward.reward_category_%s' % category).id,
                'limited_stock': bool(stock), 'stock_qty': stock, 'image_1920': images.reward_image(icon, caption),
                'company_id': False,
            })
        Transaction = env['okr.scale.point.transaction'].sudo()
        everybody = [p[0] for p in C.PEOPLE]
        for description, grants, days_ago in C.POINT_GRANTS:
            if grants == 'all:100':
                grants = {key: 100 for key in everybody}
            when = local_dt(self.today - timedelta(days=days_ago), 9)
            Transaction.create([{
                'user_id': self.users[key].id, 'points': points, 'transaction_type': 'manual',
                'description': description, 'date': when, 'company_id': self.company.id,
                'created_by_id': self.users['admin'].id,
            } for key, points in grants.items()])
        Redemption = env['okr.scale.redemption']
        for index, (person, item, quantity, state, note, reason) in enumerate(C.REDEMPTIONS):
            try:
                with env.cr.savepoint():
                    redemption = Redemption.create({
                        'user_id': self.users[person].id, 'item_id': items[item].id, 'quantity': quantity,
                        'note': note or False,
                    })
                    redemption.request_date = local_dt(self.today - timedelta(days=len(C.REDEMPTIONS) - index), 11)
                    if state in ('approved', 'delivered'):
                        redemption.action_approve()
                    if state == 'delivered':
                        redemption.action_deliver()
                    if state == 'rejected':
                        redemption.reason = reason
                        redemption.action_reject()
                    if state == 'cancelled':
                        redemption.action_cancel()
            except (UserError, ValidationError) as error:
                _logger.warning('OKR demo: redemption %s / %s skipped: %s', person, item, error)

