"""Post-install hook loading the DMAG demo.

The whole demo is generated by :class:`DemoLoader` from the plain data of
``demo_content``. Dates are computed from the day of the installation, so the
history (check-ins, weekly check-ins, kudos...) always ends "today".
"""
import base64
import logging
import random
import time as timer
from datetime import datetime, time, timedelta

from markupsafe import Markup

from odoo import Command, fields
from odoo.exceptions import UserError, ValidationError
from odoo.tools.misc import file_open

from . import demo_content as C
from . import images

_logger = logging.getLogger(__name__)

MARKER = 'okr_scale_demo.loaded'
LANG = 'vi_VN'
TZ = 'Asia/Ho_Chi_Minh'
UTC_OFFSET = 7  # Asia/Ho_Chi_Minh, no daylight saving time
LOGO = 'okr_scale/static/src/img/dmag_logo_horizontal.png'


def post_init_hook(env):
    params = env['ir.config_parameter'].sudo()
    if params.get_param(MARKER):
        _logger.info('OKR demo already loaded, skipped.')
        return
    started = timer.time()
    DemoLoader(env).load()
    params.set_param(MARKER, fields.Datetime.to_string(fields.Datetime.now()))
    _logger.info('OKR demo loaded in %.1f s', timer.time() - started)


def week_start(day):
    return day - timedelta(days=day.weekday())


def local_dt(day, hour=9, minute=0):
    """Naive UTC datetime of ``day`` at ``hour`` (Vietnam time)."""
    return datetime.combine(day, time(0, 0)) + timedelta(hours=hour - UTC_OFFSET, minutes=minute)


class DemoLoader:

    def __init__(self, env):
        self.base_env = env
        self.mail_start = env['mail.mail'].sudo().search([], order='id desc', limit=1).id or 0
        self.rnd = random.Random(2026)
        self.today = fields.Date.context_today(env['res.users'].with_context(tz=TZ))
        self.users = {}
        self.emps = {}
        self.depts = {}
        self.dept_of = {}
        self.tags = {}
        self.cycles = {}
        self.objectives = {}
        self.krs = {}
        self.kr_specs = {}
        self.kr_state = {}  # kr id -> {'count': n, 'progress': last generated progress}

    # ------------------------------------------------------------------
    # Entry point
    # ------------------------------------------------------------------
    def load(self):
        self._setup_language()
        ctx = dict(self.base_env.context, tracking_disable=True, mail_create_nolog=True, mail_create_nosubscribe=True,
                   mail_notrack=True, no_reset_password=True, no_mail_to_attendees=True, mail_auto_subscribe_no_notify=True)
        if self.base_env['res.lang']._lang_get(LANG):
            ctx['lang'] = LANG
        self.env = self.base_env(context=ctx)
        steps = [
            self._company, self._archive_odoo_demo, self._organisation, self._tags_and_cycles,
            self._year, self._q3, self._q4_objectives, self._project, self._q4_history, self._portal_checkins,
            self._q1, self._recognitions, self._feedback, self._conversations, self._rewards, self._comments,
            self._finish,
        ]
        for step in steps:
            started = timer.time()
            step()
            _logger.info('OKR demo: %s done in %.1f s', step.__name__, timer.time() - started)

    def _setup_language(self):
        Lang = self.base_env['res.lang'].with_context(active_test=False)
        lang = Lang.search([('code', '=', LANG)], limit=1)
        if lang and lang.active:
            return
        try:
            Lang._activate_lang(LANG)
            modules = self.base_env['ir.module.module'].search(
                [('state', 'in', ('installed', 'to install', 'to upgrade'))])
            modules._update_translations(LANG)
        except Exception:  # noqa: BLE001 - the demo still works in English
            _logger.warning('OKR demo: could not install the Vietnamese language', exc_info=True)

