    # Q4 history: weekly check-ins
    # ------------------------------------------------------------------
    def _q4_weeks(self):
        cycle = self.cycles['q4']
        if self.today < cycle.date_start:
            return []
        last = week_start(min(self.today, cycle.date_end))
        weeks = []
        monday = week_start(cycle.date_start)
        while monday <= last:
            weeks.append(monday)
            monday += timedelta(days=7)
        return weeks[-8:]

    def _profile_progress(self, profile, share, count):
        if profile == 'ahead':
            return 0.05 + 1.9 * share
        if profile == 'behind':
            return 0.55 * share
        if profile == 'blocked':
            return 0.3 * share
        if profile == 'stalled':
            return 0.06
        if profile == 'done':
            return 1.0 if count >= 1 else 0.4
        return 0.02 + 1.1 * share

    def _profile_confidence(self, profile, count):
        rnd = self.rnd
        return {
            'ahead': rnd.choice((8, 9, 9)),
            'on': rnd.choice((7, 7, 8)),
            'behind': rnd.choice((5, 6)),
            'blocked': 4 if count == 0 else 3,
            'stalled': 6,
            'done': rnd.choice((9, 10)),
        }.get(profile, 7)

    def _q4_history(self):
        env = self.env
        cycle = self.cycles['q4']
        weeks = self._q4_weeks()
        total_days = (cycle.date_end - cycle.date_start).days + 1
        current_week = week_start(self.today)
        Weekly = env['okr.scale.weekly']
        managed = {}
        for index, monday in enumerate(weeks):
            weeks_ago = (current_week - monday).days // 7
            is_current = weeks_ago == 0
            day = min(self.today, monday + timedelta(days=4)) if is_current else monday + timedelta(days=4)
            day = max(day, cycle.date_start)
            share = ((day - cycle.date_start).days + 1) / total_days
            for key, *_rest in C.PEOPLE:
                submitted = key in C.CURRENT_WEEK_SUBMITTERS if is_current \
                    else key not in C.MISSED_WEEKS.get(weeks_ago, [])
                if not submitted:
                    continue
                user = self.users[key]
                dept = self.dept_of[key]
                weekly = Weekly.create({
                    'user_id': user.id, 'week_start': monday, 'company_id': self.company.id,
                    'summary': self.rnd.choice(C.WEEKLY_SUMMARIES[dept]),
                    'next_plan': self.rnd.choice(C.NEXT_STEPS[dept]),
                    'help_needed': C.HELP_NEEDED.get(key) if is_current else False,
                })
                krs = env['okr.scale.key.result'].search([
                    ('owner_id', '=', user.id), ('cycle_id', '=', cycle.id), ('objective_state', '=', 'running'),
                    ('progress_method', '=', 'manual')], order='objective_id, sequence, id')
                confidences = []
                for kr in krs:
                    spec = self.kr_specs.get(kr.id)
                    if not spec:
                        continue
                    state = self.kr_state.setdefault(kr.id, {'count': 0, 'progress': 0.0})
                    profile = spec['profile']
                    if profile == 'none' or (profile == 'stalled' and state['count'] >= 1):
                        continue
                    progress = self._profile_progress(profile, share, state['count'])
                    if profile not in ('done', 'stalled'):
                        progress += self.rnd.uniform(-0.01, 0.015)
                    progress = max(state['progress'], min(1.0, max(0.0, progress)))
                    if spec['metric'] == 'boolean' and profile != 'done':
                        progress = 0.0
                    confidence = self._profile_confidence(profile, state['count'])
                    blockers = spec['blocker'] if profile == 'blocked' and state['count'] >= 1 else False
                    self._checkin(kr, user, day, self._value_for(spec, progress), confidence,
                                  achievements=self.rnd.choice(C.ACHIEVEMENTS[dept]), blockers=blockers,
                                  next_steps=weekly.next_plan, weekly=weekly)
                    state['count'] += 1
                    state['progress'] = progress
                    confidences.append(confidence)
                if confidences:
                    average = sum(confidences) / len(confidences)
                    weekly.mood = 'great' if average >= 8.5 else 'good' if average >= 7 else 'neutral' \
                        if average >= 5 else 'struggling'
                weekly._notify_managers()
                if weeks_ago >= 1:
                    managed.setdefault(key, []).append(weekly)
        self._manager_reviews(managed)

    def _manager_reviews(self, managed):
        """Managers read and comment the weekly check-ins of past weeks for some teams."""
        for key, weeklies in managed.items():
            if self.dept_of[key] not in ('kd', 'ls', 'vh', 'cskh') or key.endswith('_mgr') or key in ('ceo', 'admin'):
                continue
            manager = self._manager_user(key)
            for weekly in weeklies:
                weekly.manager_comment = self.rnd.choice(C.MANAGER_FEEDBACK)
                for checkin in weekly.checkin_ids:
                    checkin.write({
                        'state': 'reviewed', 'reviewer_id': manager.id,
                        'review_date': local_dt(checkin.date + timedelta(days=3), 9),
                        'manager_feedback': weekly.manager_comment,
                    })

    def _portal_checkins(self):
        weeks = self._q4_weeks()
        kr = self.krs['pa_patients']
        spec = self.kr_specs[kr.id]
        user = self.users['pt_edit']
        for offset, value, confidence, achievements, blockers, next_steps in C.PORTAL_CHECKINS:
            if offset >= len(weeks):
                continue
            day = min(self.today, weeks[offset] + timedelta(days=4))
            checkin = self._checkin(kr, user, day, self._round(spec, value), int(confidence), achievements,
                                    blockers, next_steps)
            self.portal_objective.message_post(
                body='%s đã check-in "%s" từ cổng khách hàng: tiến độ %.0f%%.' % (
                    user.name, kr.name, checkin.progress_after),
                author_id=user.partner_id.id, subtype_xmlid='mail.mt_note')
        self.portal_objective.message_post(
            body=Markup('<p>Tháng này phòng khám đã nhận thêm 6 ca chỉnh nha nhờ nhắc hẹn tự động. '
                        'Cảm ơn đội DMAG!</p>'),
            author_id=user.partner_id.id, message_type='comment', subtype_xmlid='mail.mt_comment')

