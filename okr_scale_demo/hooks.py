        admin = env.ref('base.user_admin')
        admin.write({
            'name': 'Lê Minh Tuấn', 'email': 'tuan.le@dmag.vn', 'lang': LANG if 'lang' in env.context else admin.lang,
            'tz': TZ, 'notification_type': 'inbox', 'image_1920': images.avatar('Lê Minh Tuấn', 1),
        })
        self.users['admin'] = admin

