    def _recognitions(self):
        env = self.env
        Recognition = env['okr.scale.recognition']
        Transaction = env['okr.scale.point.transaction']
        internal = [self.users[p[0]] for p in C.PEOPLE]
        for sender, receivers, values, points, objective, message, days_ago, likes in sorted(
                C.RECOGNITIONS, key=lambda r: -r[6]):
            when = local_dt(self.today - timedelta(days=days_ago), self.rnd.choice((9, 10, 11, 14, 15, 16)),
                            self.rnd.choice((0, 15, 30, 45)))
            recognition = Recognition.create({
                'sender_id': self.users[sender].id,
                'receiver_ids': [Command.set([self.users[r].id for r in receivers])],
                'message': Markup('<p>%s</p>') % message,
                'core_value_ids': [Command.set([env.ref('okr_scale_cfr.core_value_%s' % v).id for v in values])],
                'objective_id': self.objectives[objective].id if objective else False,
                'points': points,
                'date': when,
                'visibility': 'public',
            })
            likers = [u for u in internal if u.id != self.users[sender].id]
            self.rnd.shuffle(likers)
            recognition.like_user_ids = [Command.set([u.id for u in likers[:likes]])]
            Transaction.search([('res_model', '=', recognition._name), ('res_id', '=', recognition.id)]).write(
                {'date': when})

